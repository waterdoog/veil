import type { Analysis, Synthesis } from "../ai/backend";
import type { LedgerEntry } from "./airlock";
import { applyCodebook } from "./codebook";
import { POLICIES, type CodebookEntry, type EntityType, type PolicyName } from "./types";

export interface ReportInterview {
  id: string;
  title: string;
  raw: string;
  status: string;
  deviceMissing?: boolean;
  attested?: boolean;
  analysis?: Analysis;
}

export interface ReportStudy {
  name: string;
  policy: PolicyName;
  codebook: CodebookEntry[];
  interviews: ReportInterview[];
  synthesis?: Synthesis;
}

const esc = (s: string) => s.replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c]!);

/**
 * An audit report a researcher can hand to an ethics committee. It contains no identifiable data:
 * counts, policy, review status, and a SHA-256 of every payload that left the device.
 */
export function auditReportHtml(study: ReportStudy, ledger: LedgerEntry[], generatedAt = new Date()): string {
  const policy = POLICIES[study.policy];
  const name = applyCodebook(study.name, study.codebook, policy).redacted; // user-written: may contain a name
  const cloud = ledger.filter((e) => e.status === "ok" && e.source === "in_cloud");
  const onDevice = ledger.filter((e) => e.status === "ok" && e.source === "on_device");
  const blocked = ledger.filter((e) => e.status === "blocked");
  const kb = (n: number) => (n / 1024).toFixed(1);

  const rows = study.interviews
    .map((iv) => {
      const { spans } = applyCodebook(iv.raw, study.codebook, policy, iv.id);
      const byType = new Map<EntityType, number>();
      for (const s of spans) byType.set(s.type, (byType.get(s.type) ?? 0) + 1);
      const calls = ledger.filter((e) => e.interviewId === iv.id);
      const devCalls = calls.filter((e) => e.source === "on_device" && e.status === "ok").length;
      const sent = calls.filter((e) => e.status === "ok" && e.source === "in_cloud");
      const detection = iv.deviceMissing
        ? iv.attested
          ? "Patterns + manual review (confirmed by researcher)"
          : "Patterns only — not released"
        : devCalls
          ? `Gemini Nano on device (${devCalls} calls) + patterns`
          : "Not pseudonymised yet";
      return `<tr>
  <td>${esc(iv.id)}</td>
  <td>${detection}</td>
  <td>${spans.length}<div class="t">${[...byType].map(([t, n]) => `${t.toLowerCase()} ${n}`).join(" · ")}</div></td>
  <td>${sent.length ? sent.map((e) => `${esc(e.purpose)} · ${kb(e.bytesIn)} KB<div class="h">sha256 ${e.sha256 ?? "—"}</div>`).join("") : "nothing sent"}</td>
</tr>`;
    })
    .join("\n");

  return `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><title>Veil audit — ${esc(name)}</title>
<style>
body{font:14px/1.5 system-ui,sans-serif;color:#14213d;max-width:960px;margin:32px auto;padding:0 16px}
h1{font-family:Georgia,serif}table{border-collapse:collapse;width:100%}td,th{border-bottom:1px solid #ddd;padding:6px 8px;text-align:left;vertical-align:top}
.t{color:#666;font-size:12px}.h{font:11px ui-monospace,monospace;color:#666;word-break:break-all}.box{background:#f4f1e8;padding:12px 16px;border-radius:10px}
</style></head><body>
<h1>Pseudonymisation audit — ${esc(name)}</h1>
<p>Generated by Veil on ${generatedAt.toISOString()}. This report contains no identifiable participant data.</p>
<div class="box">
<p><b>Policy:</b> ${esc(policy.label)}</p>
<p><b>Model calls on this device (Gemini Nano):</b> ${onDevice.length} · <b>cloud calls (pseudonymised text only):</b> ${cloud.length} · <b>data sent to the cloud:</b> ${kb(cloud.reduce((a, e) => a + e.bytesIn, 0))} KB · <b>requests blocked by the airlock:</b> ${blocked.length}</p>
<p><b>Never left the device:</b> raw transcripts, photos of notes, and the codebook linking placeholders to real values (stored in this browser's IndexedDB).</p>
<p><b>Cloud storage:</b> Firestore holds pseudonymised transcripts and analysis only.</p>
</div>
<h2>Interviews</h2>
<table><thead><tr><th>Interview</th><th>Detection</th><th>Identifiers replaced</th><th>Sent to cloud</th></tr></thead>
<tbody>
${rows}
</tbody></table>
<p class="t">Each SHA-256 lets you verify a stored copy of a payload against what was sent. Session log only: calls from earlier browser sessions are not included.</p>
</body></html>`;
}

/** Pseudonymised transcripts + analysis as Markdown — the shareable research dataset. */
export function pseudonymisedMarkdown(study: ReportStudy): string {
  const policy = POLICIES[study.policy];
  const parts = [`# ${applyCodebook(study.name, study.codebook, policy).redacted} — pseudonymised dataset`, "", `Policy: ${policy.name}. Placeholders like [PERSON_1] replace identifiers; the key is kept separately.`, ""];
  for (const iv of study.interviews) {
    if (iv.status === "raw" || iv.status === "pseudonymising") continue;
    if (iv.deviceMissing && !iv.attested) continue;
    const title = applyCodebook(iv.title, study.codebook, policy, iv.id).redacted;
    parts.push(`## ${iv.id} — ${title}`, "");
    if (iv.analysis) {
      parts.push("### Analysis", "", iv.analysis.summary, "");
      for (const t of iv.analysis.themes) {
        parts.push(`**${t.name}** — ${t.description}`, "");
        for (const q of t.quotes) parts.push(`> ${q.quote}${q.timestamp ? ` (${q.timestamp})` : ""}`, "");
      }
    }
    parts.push("### Transcript", "", applyCodebook(iv.raw, study.codebook, policy, iv.id).redacted, "");
  }
  if (study.synthesis) {
    parts.push("## Cross-interview synthesis", "", study.synthesis.overview, "");
    for (const t of study.synthesis.themes) parts.push(`**${t.name}** (${t.interviews.join(", ")}) — ${t.description}`, "");
  }
  return parts.join("\n");
}

/** The re-identification key. Contains real names: the UI warns before downloading it. */
export function codebookJson(study: ReportStudy): string {
  return JSON.stringify(
    {
      warning: "This file links placeholders to real identities. Store it as your ethics approval requires; never upload it.",
      study: study.name,
      entries: study.codebook.map((e) => ({ token: e.token, real: e.real, type: e.type, interview: e.origin, kept: !e.enabled })),
    },
    null,
    1,
  );
}
